#!/usr/bin/env python3
"""Generate paired FNR-007 firmware provisioning sources.

The input JSON is intentionally not copied into the repository or build
manifest. The RP2040 source contains only the public CRC-protected record.
The ESP8285 source additionally embeds the per-device 16-byte ESP-NOW key.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import os
import struct
import zlib

MAGIC = b"FNR7"
VERSION = 1
RECORD_SIZE = 40
PLATFORM_VERSION = 1
FLAGS = 0x03
KEY_SIZE = 16


def fail(message: str) -> "NoReturn":
    raise SystemExit(message)


def parse_mac(text: str) -> bytes:
    try:
        parts = bytes(int(part, 16) for part in text.split(":"))
    except ValueError:
        fail("peer_mac must be six hexadecimal octets")
    if len(parts) != 6 or not any(parts) or (parts[0] & 1):
        fail("peer_mac must be a nonzero unicast MAC")
    return parts


def parse_u64(value: object, name: str) -> int:
    try:
        parsed = int(value, 0) if isinstance(value, str) else int(value)
    except (TypeError, ValueError):
        fail(f"{name} must be an integer or 0x-prefixed integer string")
    if parsed <= 0 or parsed > 0xFFFFFFFFFFFFFFFF:
        fail(f"{name} must be in 1..2^64-1")
    return parsed


def checked_int(doc: dict, name: str, low: int, high: int) -> int:
    value = doc.get(name)
    if not isinstance(value, int) or isinstance(value, bool) or not low <= value <= high:
        fail(f"{name} must be an integer in {low}..{high}")
    return value


def make_record(doc: dict) -> tuple[bytes, bytes, dict]:
    if set(doc) != {
        "schema_version", "config_id", "generation", "peer_mac", "channel",
        "platform_version", "profile_id", "profile_schema_version",
        "freshness_timeout_ms", "radio_key_hex"
    }:
        fail("config must contain exactly the documented FNR-007 keys")
    if doc["schema_version"] != 1:
        fail("schema_version must be 1")

    peer = parse_mac(doc["peer_mac"])
    channel = checked_int(doc, "channel", 1, 14)
    platform = checked_int(doc, "platform_version", 1, 255)
    profile = checked_int(doc, "profile_id", 1, 255)
    profile_schema = checked_int(doc, "profile_schema_version", 1, 255)
    freshness = checked_int(doc, "freshness_timeout_ms", 1, 0x7FFFFFFF)
    generation = checked_int(doc, "generation", 1, 0xFFFFFFFF)
    config_id = parse_u64(doc["config_id"], "config_id")

    if platform != PLATFORM_VERSION:
        fail("platform_version must match frozen FNR platform v1")
    key_text = doc["radio_key_hex"]
    if not isinstance(key_text, str):
        fail("radio_key_hex must be a 32-hex-character string")
    try:
        key = bytes.fromhex(key_text)
    except ValueError:
        fail("radio_key_hex must contain hexadecimal bytes")
    if len(key) != KEY_SIZE:
        fail("radio_key_hex must contain exactly 16 bytes")
    if not any(key):
        fail("radio_key_hex must not be the all-zero key")

    record = bytearray(RECORD_SIZE)
    record[0:4] = MAGIC
    record[4] = VERSION
    record[5] = FLAGS
    record[6] = channel
    record[7] = platform
    record[8] = profile
    record[9] = profile_schema
    record[10:16] = peer
    struct.pack_into("<I", record, 16, freshness)
    struct.pack_into("<Q", record, 20, config_id)
    struct.pack_into("<I", record, 28, generation)
    struct.pack_into("<I", record, 36, zlib.crc32(record[:36]) & 0xFFFFFFFF)

    redacted = {
        "schema_version": 1,
        "config_id": f"0x{config_id:016x}",
        "generation": generation,
        "peer_mac": ":".join(f"{b:02x}" for b in peer),
        "channel": channel,
        "platform_version": platform,
        "profile_id": profile,
        "profile_schema_version": profile_schema,
        "freshness_timeout_ms": freshness,
        "encryption_required": True,
        "radio_key_present": True,
        "public_record_sha256": hashlib.sha256(record).hexdigest(),
    }
    return bytes(record), key, redacted


def byte_array(data: bytes, indent: str = "    ") -> str:
    rows = []
    for offset in range(0, len(data), 12):
        rows.append(indent + ", ".join(f"0x{b:02x}" for b in data[offset:offset + 12]) + ",")
    return "\n".join(rows)


def rp_source(record: bytes) -> str:
    return f'''/* Generated by tools/generate_provisioning.py. No radio key is present. */
#include "fnr/provisioning_image.h"

static const uint8_t public_record[] = {{
{byte_array(record)}
}};

const uint8_t *fnr_provisioning_image_public(size_t *size) {{
    if (size != NULL) *size = sizeof(public_record);
    return public_record;
}}
'''


def esp_source(record: bytes, key: bytes) -> str:
    return f'''/* Generated by tools/generate_provisioning.py.
 * Contains a per-device ESP-NOW key. Do not commit generated output. */
#include "fnr/provisioning_image.h"
#include "provisioning_image.h"

static const uint8_t public_record[] = {{
{byte_array(record)}
}};
static const uint8_t radio_key[] = {{
{byte_array(key)}
}};

const uint8_t *fnr_provisioning_image_public(size_t *size) {{
    if (size != NULL) *size = sizeof(public_record);
    return public_record;
}}

const uint8_t *fnr_provisioning_image_radio_key(size_t *size) {{
    if (size != NULL) *size = sizeof(radio_key);
    return radio_key;
}}
'''


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", required=True, type=pathlib.Path)
    parser.add_argument("--out-dir", required=True, type=pathlib.Path)
    args = parser.parse_args()

    doc = json.loads(args.config.read_text(encoding="utf-8"))
    if not isinstance(doc, dict):
        fail("config root must be an object")
    record, key, redacted = make_record(doc)

    args.out_dir.mkdir(parents=True, exist_ok=True)
    rp_path = args.out_dir / "rp_provisioning_image.c"
    esp_path = args.out_dir / "esp_provisioning_image.cpp"
    redacted_path = args.out_dir / "provisioning-redacted.json"
    rp_path.write_text(rp_source(record), encoding="utf-8")
    esp_path.write_text(esp_source(record, key), encoding="utf-8")
    os.chmod(esp_path, 0o600)
    redacted_path.write_text(
        json.dumps(redacted, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(redacted, sort_keys=True))


if __name__ == "__main__":
    main()
